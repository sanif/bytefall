package data

import (
	"strings"
	"sync"
	"time"
)

// DNSCache maps IP addresses to domain names learned from DNS queries
type DNSCache struct {
	ipToDomain map[string]dnsEntry
	mu         sync.RWMutex
}

type dnsEntry struct {
	domain string
	expiry time.Time
}

// NewDNSCache creates a new DNS cache
func NewDNSCache() *DNSCache {
	return &DNSCache{
		ipToDomain: make(map[string]dnsEntry),
	}
}

// Add adds a domain->IP mapping (called when we see a DNS response)
func (d *DNSCache) Add(ip, domain string) {
	d.mu.Lock()
	defer d.mu.Unlock()

	// Cache for 5 minutes
	d.ipToDomain[ip] = dnsEntry{
		domain: domain,
		expiry: time.Now().Add(5 * time.Minute),
	}
}

// Lookup returns the domain for an IP if known
func (d *DNSCache) Lookup(ip string) (string, bool) {
	d.mu.RLock()
	defer d.mu.RUnlock()

	entry, ok := d.ipToDomain[ip]
	if !ok {
		return "", false
	}

	if time.Now().After(entry.expiry) {
		return "", false
	}

	return entry.domain, true
}

// AddFromSNI adds a mapping when we see SNI in TLS handshake
func (d *DNSCache) AddFromSNI(ip, domain string) {
	d.Add(ip, domain)
}

// Cleanup removes expired entries
func (d *DNSCache) Cleanup() {
	d.mu.Lock()
	defer d.mu.Unlock()

	now := time.Now()
	for ip, entry := range d.ipToDomain {
		if now.After(entry.expiry) {
			delete(d.ipToDomain, ip)
		}
	}
}

