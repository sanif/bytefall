// LookupWellKnown checks if IP belongs to a well-known service
func LookupWellKnown(ip string) string {
	for _, entry := range WellKnownPrefixes {
		if strings.HasPrefix(ip, entry.prefix) {
			return entry.domain
		}
	}
	return ""
}
